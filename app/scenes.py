def get_scene(name: str) -> dict:
    if name not in SCENES:
        raise KeyError(f"Сцена '{name}' не найдена")
    return SCENES[name]

def visible_choices(scene: dict, state: dict) -> list[dict]:
    visible = []
    for choice in scene["choices"]:
        condition = choice.get("condition")
        if condition is None:
            visible.append(choice)
            continue
        else:
            ok = True
            for key, value in condition.items():
                if key == "flag_absent":
                    if state["flags"].get(value):
                        ok = False
                elif key == "inventory_absent":
                    if state["inventory"].get(value):
                        ok = False
                elif key == "money_at_least":
                    if state["money"] < value: 
                        ok = False
                elif key == "inventory_has_all":
                    for item in value:                       # value — список предметов
                        if not state["inventory"].get(item):
                            ok = False
                elif key == "flag_present":
                    if not state["flags"].get(value):
                        ok = False
                elif key == "inventory_not_has_all":
                    if all(state["inventory"].get(item) for item in value):
                        ok = False
            if ok:
                visible.append(choice)
    return visible

def apply_effects(state: dict, gives: Optional[dict]) -> None:
    if not gives:
        return
    if "flags" in gives:
        for name, value in gives["flags"].items():
            state["flags"][name] = value
    if "money" in gives:
        state["money"] += gives["money"]
    if "inventory" in gives:
        for item, qty in gives["inventory"].items():
            state["inventory"][item] = state["inventory"].get(item, 0) + qty
            if state["inventory"][item] <= 0:
                del state["inventory"][item]

def make_choice(current: str, choice_index: int, state: dict) -> tuple[str, dict]:
    scene = get_scene(current)
    visible = visible_choices(scene, state)
    if not visible:
        raise ValueError(f"Сцена '{current}' — нет доступных выборов")
    if choice_index < 0 or choice_index >= len(visible):
        raise IndexError(f"Неверный индекс выбора: {choice_index}")
    choice = visible[choice_index]
    return choice["next"], choice